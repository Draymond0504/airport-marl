"""Render a deterministic eight-aircraft MAPPO rollout as a GIF.

The test case is stored in the manifest generated by
``generate_banked_schedule.py``.  It is selected by schedule order rather
than by a successful model outcome, so the animation remains reproducible and
auditable.
"""

from __future__ import annotations

import argparse
import io
import json
import random
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import torch
from PIL import Image

from configs.config import Config
from env.marl_env import MARLEnv
from env.taxi_graph_env import NodeType
from trainer.mappo_improved import MAPPOTrainerImproved


COLORS = ["#d1495b", "#00798c", "#30638e", "#f4a261", "#7b2cbf", "#2a9d8f", "#e76f51", "#3a506b"]


def _set_seed(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)


def _coordinates(env: MARLEnv, agent_id: int) -> tuple[float, float]:
    graph = env.graph_env
    if not graph.agent_on_edge[agent_id] or graph.edge_idx[agent_id] is None:
        return graph.nodes[graph.agent_positions[agent_id]].position
    edge = graph.edges[graph.edge_idx[agent_id]]
    x0, y0 = graph.nodes[edge.start].position
    x1, y1 = graph.nodes[edge.end].position
    progress = graph.progress[agent_id]
    return x0 + (x1 - x0) * progress, y0 + (y1 - y0) * progress


def _draw(ax: plt.Axes, env: MARLEnv, step: int, completed: int, case: dict) -> None:
    graph = env.graph_env
    ax.clear()
    unique_edges = {(min(edge.start, edge.end), max(edge.start, edge.end)) for edge in graph.edges}
    for start, end in unique_edges:
        x0, y0 = graph.nodes[start].position
        x1, y1 = graph.nodes[end].position
        edge_index = graph.get_edge_between(start, end)
        closed = edge_index is not None and graph.edges[edge_index].closed
        ax.plot([x0, x1], [y0, y1], color="#a0a8b0" if not closed else "#b22222", lw=0.8, zorder=1)

    for node_id, node in graph.nodes.items():
        x, y = node.position
        if node.type == NodeType.GATE:
            ax.scatter(x, y, s=24, facecolors="white", edgecolors="#737373", linewidths=0.6, zorder=2)
        elif node_id in (100, 105, 200, 205):
            ax.scatter(x, y, s=32, marker="s", c="#4b5563", zorder=2)

    for agent_id in range(env.num_agents):
        color = COLORS[agent_id % len(COLORS)]
        goal = graph.agent_goals[agent_id]
        gx, gy = graph.nodes[goal].position
        ax.scatter(gx, gy, s=135, facecolors="none", edgecolors=color, linewidths=1.1, alpha=0.55, zorder=3)

        path = env.agents[agent_id].planned_path
        for left, right in zip(path, path[1:]):
            if left in graph.nodes and right in graph.nodes:
                x0, y0 = graph.nodes[left].position
                x1, y1 = graph.nodes[right].position
                ax.plot([x0, x1], [y0, y1], color=color, lw=1.0, alpha=0.22, zorder=2)

        x, y = _coordinates(env, agent_id)
        delay = graph.start_delays[agent_id]
        crashed = graph.crashed[agent_id]
        finished = graph.done[agent_id] and not crashed
        alpha = 0.25 if delay > 0 else 1.0
        marker = "X" if crashed else ("*" if finished else "o")
        size = 90 if marker == "o" else 135
        ax.scatter(x, y, s=size, marker=marker, c=color, edgecolors="white", linewidths=0.9, alpha=alpha, zorder=6)
        label = case["flights"][agent_id]["flight_number"][-3:]
        ax.text(x, y, label, fontsize=6.5, ha="center", va="center", color="white", fontweight="bold", zorder=7)

    crashes = int(sum(graph.crashed))
    active = int(sum(not graph.done[index] and graph.start_delays[index] <= 0 for index in range(env.num_agents)))
    ax.set_title(
        f"MAPPO-Guided | step {step} | completed {completed}/{env.num_agents} | active {active} | crashes {crashes}",
        fontsize=11,
        pad=10,
    )
    ax.text(
        0.01,
        0.01,
        "circles: active aircraft   rings: assigned destinations   faint lines: A* references",
        transform=ax.transAxes,
        fontsize=7,
        color="#374151",
    )
    ax.set_aspect("equal")
    ax.set_axis_off()
    ax.margins(0.08)


def render(args: argparse.Namespace) -> dict:
    _set_seed(args.seed)
    manifest = json.loads(Path(args.manifest).read_text(encoding="utf-8"))
    case = manifest["visualization_case"]
    if len(case["starts"]) != 8:
        raise ValueError("The GIF renderer requires an eight-aircraft case")

    config = Config.from_yaml(args.config)
    if config.env.num_agents != 8:
        raise ValueError("Use an eight-agent configuration for this GIF")
    env = MARLEnv(config)
    trainer = MAPPOTrainerImproved(
        num_agents=env.num_agents,
        obs_dim=env.obs_dim,
        action_dim=env.action_dim,
        global_state_dim=env.global_state_dim,
        hidden_dim=config.training.hidden_dim,
        device=args.device,
        critic_state_schema=env.critic_state_schema,
    )
    trainer.load(args.model, load_optimizer=False)

    observations, masks = env.reset(
        starts=case["starts"],
        goals=case["goals"],
        delays=case["delays"],
    )
    global_state = env.get_global_state()
    figure, axis = plt.subplots(figsize=(10, 8), constrained_layout=True)
    frames: list[Image.Image] = []

    def capture(step: int) -> None:
        completed = sum(
            env.graph_env.done[index] and not env.graph_env.crashed[index]
            for index in range(env.num_agents)
        )
        _draw(axis, env, step, int(completed), case)
        buffer = io.BytesIO()
        figure.savefig(buffer, format="png", dpi=args.dpi)
        buffer.seek(0)
        frames.append(Image.open(buffer).convert("P", palette=Image.Palette.ADAPTIVE))
        buffer.close()

    capture(0)
    total_reward = 0.0
    final_step = 0
    max_active = 0
    for step in range(1, min(args.max_steps, config.env.max_steps) + 1):
        actions, _, _ = trainer.select_actions(observations, masks, global_state, deterministic=True)
        observations, rewards, dones, masks, _ = env.step(actions)
        global_state = env.get_global_state()
        total_reward += float(sum(rewards))
        final_step = step
        max_active = max(
            max_active,
            int(sum(
                not env.graph_env.done[index]
                and env.graph_env.start_delays[index] <= 0
                for index in range(env.num_agents)
            )),
        )
        if step % args.frame_stride == 0 or all(dones):
            capture(step)
        if all(dones):
            break

    if not frames:
        raise RuntimeError("No animation frames were captured")
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    frames[0].save(
        output,
        save_all=True,
        append_images=frames[1:],
        duration=max(int(1000 / args.fps), 1),
        loop=0,
        optimize=False,
    )
    plt.close(figure)

    result = {
        "model": args.model,
        "config": args.config,
        "manifest": args.manifest,
        "seed": args.seed,
        "deterministic": True,
        "steps": final_step,
        "completed": int(sum(env.graph_env.done[index] and not env.graph_env.crashed[index] for index in range(env.num_agents))),
        "crashed": int(sum(env.graph_env.crashed)),
        "max_active": max_active,
        "total_reward": round(total_reward, 3),
        "frame_count": len(frames),
        "output": str(output),
    }
    output.with_suffix(".json").write_text(json.dumps(result, indent=2), encoding="utf-8")
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description="Render a deterministic MAPPO GIF")
    parser.add_argument("--manifest", default="data/paper_schedule_banked_v1_manifest.json")
    parser.add_argument("--config", default="configs/fine_tune_8agents.yaml")
    parser.add_argument("--model", default="checkpoints/stage3_priorityfix_v1/best_eval.pt")
    parser.add_argument("--output", default="results/figures/mappo_banked_peak_case.gif")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--fps", type=int, default=10)
    parser.add_argument("--frame-stride", type=int, default=3)
    parser.add_argument("--max-steps", type=int, default=500)
    parser.add_argument("--dpi", type=int, default=100)
    parser.add_argument("--device", default="cpu")
    args = parser.parse_args()
    result = render(args)
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
