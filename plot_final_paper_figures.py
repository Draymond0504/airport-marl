"""Generate the three event-faithful paper figures from final rolling results.

This script deliberately uses the execution logs generated by
``paper_rolling_executor.py``.  It does not reconstruct traffic from planned
paths: closure maps use observed completed edge traversals and the priority
plot uses the actual event-relative micro frames.
"""

from __future__ import annotations

import argparse
import csv
import json
from collections import defaultdict
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.cm import ScalarMappable
from matplotlib.colors import Normalize
import numpy as np

from env.taxi_graph_env import TaxiGraphEnv


METHODS = {
    "MAPPO": {"label": "MAPPO-Guided", "color": "#007C91"},
    "FCFS": {"label": "FCFS+A*", "color": "#C25B35"},
}
INK = "#263238"
ROAD = "#CCD6DD"
GATE = "#8E9AAF"
VIP = "#D97706"
OTHER = "#7A8790"


def read_json(path: Path) -> dict:
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


def read_csv(path: Path) -> list[dict]:
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def layout_f_geometry() -> tuple[dict[int, tuple[float, float]], list[tuple[int, int]]]:
    env = TaxiGraphEnv(
        num_agents=1,
        max_steps=1,
        close_prob=0.0,
        delay_prob=0.0,
        priority_prob=0.0,
        layout="F",
        auto_speed=True,
        random_flow_mix=False,
    )
    pos = {int(node_id): node.position for node_id, node in env.nodes.items()}
    edges = set()
    for edge in env.edges:
        key = tuple(sorted((int(edge.start), int(edge.end))))
        edges.add(key)
    return pos, sorted(edges)


def draw_network(ax, pos: dict[int, tuple[float, float]], edges: list[tuple[int, int]]) -> None:
    for start, end in edges:
        x0, y0 = pos[start]
        x1, y1 = pos[end]
        is_gate_link = start < 30 or end < 30 or start >= 2000 or end >= 2000
        ax.plot(
            [x0, x1], [y0, y1],
            color=GATE if is_gate_link else ROAD,
            linewidth=0.65 if is_gate_link else 1.1,
            zorder=1,
        )
    ax.set_aspect("equal", adjustable="box")
    ax.set_axis_off()


def baseline_figure(root: Path, out_dir: Path) -> None:
    summaries = {
        method: read_json(root / "baseline" / f"{method}_summary.json")
        for method in METHODS
    }
    specs = [
        ("safe_completion_rate_pct", "Safe completion (%)", "Safe completion", "{:.1f}%"),
        ("success_count", "Completed flights", "Completed flights", "{:.0f}"),
        ("throughput_per_hour", "Throughput (flights/h)", "System throughput", "{:.2f}"),
        ("avg_taxi_min", "Mean taxi time (min)", "Mean taxi time among completed flights", "{:.2f}"),
    ]
    fig, axes = plt.subplots(2, 2, figsize=(10.4, 6.7))
    x = np.arange(len(METHODS))
    for ax, (key, ylabel, title, fmt) in zip(axes.flat, specs):
        values = [float(summaries[m].get(key, 0.0) or 0.0) for m in METHODS]
        colors = [METHODS[m]["color"] for m in METHODS]
        bars = ax.bar(x, values, width=0.58, color=colors, alpha=0.9)
        for bar, method, value in zip(bars, METHODS, values):
            label = fmt.format(value)
            if key == "avg_taxi_min":
                label += f"\nn={summaries[method]['success_count']}"
            ax.text(
                bar.get_x() + bar.get_width() / 2,
                bar.get_height() + max(0.018 * max(values, default=1), 0.02),
                label,
                ha="center", va="bottom", fontsize=8,
            )
        ax.set_title(title, fontsize=10, color=INK, pad=12)
        ax.set_ylabel(ylabel, color=INK)
        ax.set_xticks(x, [METHODS[m]["label"] for m in METHODS])
        ax.spines[["top", "right"]].set_visible(False)
        ax.grid(axis="y", alpha=0.18, linewidth=0.6)
        ax.set_axisbelow(True)
        if key == "safe_completion_rate_pct":
            ax.set_ylim(0, 112)
        elif key == "avg_taxi_min":
            ax.set_ylim(0, max(values) * 1.35)
    fig.suptitle("Baseline rolling-schedule performance", fontsize=14, color=INK, y=0.99)
    fig.text(
        0.5, 0.015,
        "All metrics use the same 363-flight schedule. Taxi time is conditional on completed flights.",
        ha="center", fontsize=8, color="#5F6B72",
    )
    fig.tight_layout(rect=[0, 0.045, 1, 0.95])
    fig.savefig(out_dir / "fig_baseline_comparison.png", dpi=300, bbox_inches="tight")
    plt.close(fig)


def closure_event(root: Path) -> dict:
    payload = read_json(root / "closure" / "MAPPO_events.json")
    events = [event for event in payload.get("events", []) if event.get("type") == "closure"]
    if not events:
        raise RuntimeError("No closure event was logged in MAPPO_events.json.")
    return min(events, key=lambda event: int(event["step"]))


def window_counts(rows: list[dict], start: int, end: int) -> dict[tuple[int, int], int]:
    counts: dict[tuple[int, int], int] = defaultdict(int)
    for row in rows:
        step = int(float(row["step"]))
        if start <= step < end:
            key = tuple(sorted((int(row["edge_start"]), int(row["edge_end"]))))
            counts[key] += 1
    return dict(counts)


def closure_edge_flow_figure(root: Path, out_dir: Path) -> None:
    event = closure_event(root)
    trigger = int(event["step"])
    duration = int(event["duration"])
    closed = tuple(sorted(int(v) for v in event["edge_nodes"]))
    windows = [("Before closure", trigger - duration, trigger), ("Closure active", trigger, trigger + duration)]
    data = {
        method: read_csv(root / "closure" / f"{method}_edge_traversals.csv")
        for method in METHODS
    }
    counts = {
        (method, label): window_counts(data[method], start, end)
        for method in METHODS
        for label, start, end in windows
    }
    vmax = max((value for values in counts.values() for value in values.values()), default=1)
    vmax = max(vmax, 1)
    norm = Normalize(vmin=0, vmax=vmax)
    cmap = plt.get_cmap("YlOrRd")
    pos, edges = layout_f_geometry()

    fig = plt.figure(figsize=(12.0, 8.3))
    grid = fig.add_gridspec(2, 3, width_ratios=[1, 1, 0.06], hspace=0.20, wspace=0.08)
    axes = np.array([
        [fig.add_subplot(grid[0, 0]), fig.add_subplot(grid[0, 1])],
        [fig.add_subplot(grid[1, 0]), fig.add_subplot(grid[1, 1])],
    ])
    colorbar_ax = fig.add_subplot(grid[:, 2])
    for row, method in enumerate(METHODS):
        for col, (label, start, end) in enumerate(windows):
            ax = axes[row, col]
            draw_network(ax, pos, edges)
            local = counts[(method, label)]
            for edge, value in local.items():
                if edge[0] not in pos or edge[1] not in pos:
                    continue
                x0, y0 = pos[edge[0]]
                x1, y1 = pos[edge[1]]
                ax.plot([x0, x1], [y0, y1], color=cmap(norm(value)), linewidth=1.2 + 4.5 * value / vmax,
                        solid_capstyle="round", zorder=3)
            if label == "Closure active":
                x0, y0 = pos[closed[0]]
                x1, y1 = pos[closed[1]]
                ax.plot([x0, x1], [y0, y1], color="#7F1D1D", linewidth=5.4,
                        linestyle=(0, (2, 1)), zorder=5)
            total = sum(local.values())
            ax.set_title(f"{METHODS[method]['label']} | {label}\n{total} completed edge traversals", fontsize=10, color=INK)
            ax.text(0.02, 0.03, f"steps {start}-{end - 1}", transform=ax.transAxes,
                    fontsize=8, color="#4B5563", ha="left", va="bottom")
    colorbar = fig.colorbar(ScalarMappable(norm=norm, cmap=cmap), cax=colorbar_ax)
    colorbar.set_label("Completed traversals per undirected segment (800-step window)")
    fig.suptitle(
        f"Observed edge use around closure of link {closed[0]}-{closed[1]}",
        fontsize=14, color=INK, y=0.985,
    )
    fig.text(0.5, 0.012, "The dashed dark-red segment is unavailable only in the right column; all panels share one colour scale.",
             ha="center", fontsize=8, color="#5F6B72")
    fig.subplots_adjust(left=0.025, right=0.95, bottom=0.08, top=0.90)
    fig.savefig(out_dir / "fig_closure_edge_flow.png", dpi=300, bbox_inches="tight")
    plt.close(fig)


def local_distance_tracks(payload: dict) -> tuple[dict[int, list[tuple[float, float]]], int, float]:
    """Integrate each observed agent's local motion from the micro-log.

    The y-axis is deliberately not a node ID.  Each curve begins at zero when
    that aircraft first appears in the event window and accumulates its
    observed speed; this exposes pauses and subsequent movement without
    implying that different routes share a physical longitudinal coordinate.
    """
    event_step = int(payload["event_step"])
    time_scale = float(payload.get("time_scale", 1.0))
    first_step = event_step - int(payload.get("window_before_steps", 100))
    last_step = event_step + int(payload.get("window_after_steps", 200))
    tracks: dict[int, list[tuple[float, float]]] = defaultdict(list)
    distance: dict[int, float] = defaultdict(float)
    previous_step: dict[int, int] = {}
    previous_speed: dict[int, float] = {}
    for frame in sorted(payload.get("frames", []), key=lambda item: int(item["step"])):
        step = int(frame["step"])
        if step < first_step or step > last_step:
            continue
        rel_min = (step - event_step) * time_scale / 60.0
        for agent in frame.get("agents", []):
            flight = int(agent["flight_index"])
            if flight in previous_step:
                delta = max(0, step - previous_step[flight])
                distance[flight] += previous_speed[flight] * delta
            tracks[flight].append((rel_min, distance[flight]))
            previous_step[flight] = step
            previous_speed[flight] = float(agent.get("speed", 0.0) or 0.0)
    return dict(tracks), int(payload["target_flight_index"]), time_scale


def priority_time_space_figure(root: Path, out_dir: Path) -> None:
    payloads = {method: read_json(root / "priority" / f"{method}_micro_priority.json") for method in METHODS}
    fig, axes = plt.subplots(1, 2, figsize=(12.0, 5.2), sharey=True)
    for ax, method in zip(axes, METHODS):
        tracks, vip, _ = local_distance_tracks(payloads[method])
        for flight, points in tracks.items():
            if not points:
                continue
            x, y = zip(*points)
            if flight == vip:
                ax.plot(x, y, color=VIP, linewidth=3.0, zorder=4, label=f"Priority flight {vip}")
                ax.scatter([x[0], x[-1]], [y[0], y[-1]], color=VIP, edgecolor="white", linewidth=0.6, s=34, zorder=5)
            else:
                ax.plot(x, y, color=OTHER, alpha=0.60, linewidth=1.1, zorder=2, label="Concurrent flights")
        handles, labels = ax.get_legend_handles_labels()
        unique = dict(zip(labels, handles))
        ax.legend(unique.values(), unique.keys(), frameon=False, loc="upper left", fontsize=8)
        ax.axvline(0, color="#374151", linestyle="--", linewidth=1.0, zorder=1)
        ax.axvspan(0, 300 * float(payloads[method].get("time_scale", 1.0)) / 60.0,
                   color=VIP, alpha=0.08, zorder=0)
        ax.set_title(METHODS[method]["label"], color=INK)
        ax.set_xlabel("Time relative to priority boost (min)")
        ax.grid(alpha=0.20, linewidth=0.6)
        ax.spines[["top", "right"]].set_visible(False)
    axes[0].set_ylabel("Local cumulative travel distance (graph units)")
    fig.suptitle("Event-local movement response to a priority boost", fontsize=14, color=INK, y=0.995)
    fig.text(
        0.5, 0.01,
        "Each aircraft is re-zeroed at its first observed frame; horizontal segments indicate a local hold. Shading denotes the 300-step boost interval.",
        ha="center", fontsize=8, color="#5F6B72",
    )
    fig.tight_layout(rect=[0, 0.045, 1, 0.95])
    fig.savefig(out_dir / "fig_priority_time_space.png", dpi=300, bbox_inches="tight")
    plt.close(fig)


def delay_wait_boxplot(root: Path, out_dir: Path) -> None:
    """Plot the requested delay-scenario boxplot in seconds to retain scale."""
    values: dict[str, list[float]] = {}
    for method in METHODS:
        rows = read_csv(root / "delay" / f"{method}_per_agent.csv")
        cleaned = []
        for row in rows:
            if str(row.get("crashed", "")).lower() in {"1", "true"}:
                continue
            onroute = float(row.get("onroute_wait_sec") or 0.0)
            queue = float(row.get("wait_time_min") or 0.0) * 60.0
            cleaned.append(onroute + queue)
        values[method] = cleaned
    fig, ax = plt.subplots(figsize=(7.0, 5.0))
    ordered = list(METHODS)
    data = [values[m] for m in ordered]
    box = ax.boxplot(data, patch_artist=True, tick_labels=[METHODS[m]["label"] for m in ordered], showfliers=True)
    for patch, method in zip(box["boxes"], ordered):
        patch.set_facecolor(METHODS[method]["color"])
        patch.set_alpha(0.72)
    means = [float(np.mean(item)) if item else 0.0 for item in data]
    ax.scatter(np.arange(1, len(data) + 1), means, marker="D", color="#202124", s=32, zorder=4, label="Mean")
    ymax = max((max(item) for item in data if item), default=1.0)
    for index, (method, mean) in enumerate(zip(ordered, means), start=1):
        ax.text(index, mean + max(ymax * 0.025, 0.08), f"mean={mean:.2f} s\nn={len(values[method])}",
                ha="center", va="bottom", fontsize=8)
    ax.set_ylim(bottom=0, top=max(ymax * 1.17, 1.0))
    ax.set_ylabel("Total waiting time (s)")
    ax.set_title("Waiting-time distribution under delayed release", color=INK, pad=12)
    ax.grid(axis="y", alpha=0.18, linewidth=0.6)
    ax.set_axisbelow(True)
    ax.spines[["top", "right"]].set_visible(False)
    ax.legend(frameon=False)
    fig.tight_layout()
    fig.savefig(out_dir / "fig_delay_wait_boxplot.png", dpi=300, bbox_inches="tight")
    plt.close(fig)


def main() -> None:
    parser = argparse.ArgumentParser(description="Create final empirical paper figures from rolling experiment logs.")
    parser.add_argument("--result-root", default="results/paper_final")
    parser.add_argument("--output-dir", default=None)
    args = parser.parse_args()
    root = Path(args.result_root)
    out_dir = Path(args.output_dir) if args.output_dir else root / "figures"
    out_dir.mkdir(parents=True, exist_ok=True)
    baseline_figure(root, out_dir)
    closure_edge_flow_figure(root, out_dir)
    priority_time_space_figure(root, out_dir)
    delay_wait_boxplot(root, out_dir)
    print(f"[OK] Final empirical figures written to {out_dir}")


if __name__ == "__main__":
    main()
